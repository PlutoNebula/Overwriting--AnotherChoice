REVIEW_SYSTEM = """【任务类型】review
你是一名资深审校，负责用「原始分块分析结果」反向核对「成稿」，找出质量问题。

你将收到：全部片段的结构化分析结果（JSON 数组）与成稿（各文件的 Markdown 内容）。

请从五个维度核对并**只输出一个合法的 JSON 对象**：

{
  "通过": true 或 false,
  "评分": {"一致性": 1到5, "完整性": 1到5, "准确性": 1到5, "去重": 1到5, "可读性": 1到5},
  "问题清单": [
    {"位置": "人物信息/张三.md", "严重度": "高|中|低", "描述": "问题描述", "建议": "修改建议"}
  ],
  "修订意见": "给成稿环节的具体修改指令（无问题时留空字符串）"
}

核对标准：
1. 一致性：梗概 ↔ 人物经历 ↔ 世界书时间线 是否相互矛盾。
2. 完整性：是否有遗漏的关键情节 / 主要人物 / 世界事实（相对原始分析缺失）。
3. 准确性：成稿是否出现幻觉（成稿内容在原始分析中找不到依据）。
4. 去重：同名角色/同义地点是否重复或命名不统一。
5. 可读性：结构、格式、语言是否规范。

判定：若存在「高」严重度问题，或「中」严重度问题 ≥ 2 个，则「通过」应为 false，并给出明确「修订意见」；否则「通过」为 true。
"""


def build_assemble_user(work_name: str, analyses: list[dict], feedback: str = "") -> str:
    parts = [f"作品名：{work_name}\n", "=== 分块分析结果 ===", json.dumps(analyses, ensure_ascii=False, indent=2)]
    if feedback:
        parts.append("\n=== 上一轮修订意见 ===")
        parts.append(feedback)
    return "\n".join(parts)


def build_review_user(analyses: list[dict], outputs: dict[str, str]) -> str:
    parts = [
        "=== 原始分块分析结果 ===",
        json.dumps(analyses, ensure_ascii=False, indent=2),
        "\n=== 成稿内容 ===",
        json.dumps(outputs, ensure_ascii=False, indent=2),
    ]
    return "\n".join(parts)


